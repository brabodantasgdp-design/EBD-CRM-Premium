/**
 * PREPARAÇÃO MULTI-TENANT & SUPABASE RLS (DOCUMENTAÇÃO):
 * 
 * Em uma arquitetura de produção com backend real (Supabase / PostgreSQL):
 * - Todas as operações de banco de dados dependerão das entidades relacionais:
 *   - `organizations` (Empresa/Tenant principal)
 *   - `organization_members` (Vínculo de usuários com perfis e permissões)
 *   - `leads` (Tabela principal com a chave estrangeira `organization_id`)
 *   - `lead_tags` e `tags` (Relacionamento N:N de etiquetas)
 *   - `activities` e `tasks` (Histórico e próximos compromissos vinculados a `lead_id`)
 *   - `custom_fields` e `custom_field_values` (Campos dinâmicos por tenant)
 * 
 * - RLS (Row Level Security):
 *   As regras no Supabase garantem que `auth.uid()` só acesse dados onde `organization_id`
 *   corresponde à empresa autorizada na tabela `organization_members`.
 *   O isolamento de dados NUNCA é delegado apenas ao código client-side React.
 * 
 * Este arquivo fornece os dados simulados centralizados para a prototipação do módulo de Gestão de Leads.
 */

