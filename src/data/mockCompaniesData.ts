export function calculateCompanySummaryMetrics(companies: CompanyItem[]) {
  const totalCompanies = companies.length;
  const customers = companies.filter((c) => c.status === "cliente").length;
  const prospects = companies.filter((c) => c.status === "prospect").length;

  const withOpenDeals = companies.filter((c) => {
    if (!c.deals || c.deals.length === 0) return false;
    return c.deals.some((d) => d.status === "open");
  }).length;

  const withoutActivity = companies.filter(
    (c) => c.daysWithoutActivity && c.daysWithoutActivity > 30
  ).length;

  const rawPipeline = companies.reduce((acc, c) => {
    if (!c.deals) return acc;
    const openSum = c.deals
      .filter((d) => d.status === "open")
      .reduce((sum, d) => sum + (d.value || 0), 0);
    return acc + openSum;
  }, 0);

  const formattedPipelineValue = `R$ ${rawPipeline.toLocaleString("pt-BR")}`;

  return {
    totalCompanies,
    customers,
    prospects,
    withOpenDeals,
    withoutActivity,
    totalPipelineValue: rawPipeline,
    formattedPipelineValue,
  };
}

